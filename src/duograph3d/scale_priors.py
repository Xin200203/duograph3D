from __future__ import annotations

"""Physical scale priors for evaluator-facing semantic-authority checks.

The carrier-readout failure family behind the E70 gains is one physical
principle: a small-object label (tissue-paper, bin) sitting on a geometry
carrier whose extent the label cannot plausibly reach.  Instead of hand-written
`source:target:threshold` rules, these helpers derive repairs from a per-label
max-extent prior plus the object's own multi-view declared-label distribution.

Provenance of DEFAULT_MAX_EXTENT_PRIORS: commonsense physical size upper bounds
(longest bounding-box side, meters) generated by a language model from the class
names alone, frozen before any evaluation, and deliberately generous — the
violation check should only fire when an object is clearly larger than its
readout label could plausibly be.  No Replica ground truth, scene identity, or
evaluation feedback was used to set these numbers.
"""


